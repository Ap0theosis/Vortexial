let smithItems = [
    ['stalwart_dungeons:wooden_hammer'],['stalwart_dungeons:stone_hammer'],['stalwart_dungeons:iron_hammer'],
    ['stalwart_dungeons:golden_hammer'],['stalwart_dungeons:diamond_hammer'],['stalwart_dungeons:netherite_hammer'],
    ['stalwart_dungeons:tungsten_hammer'],['stalwart_dungeons:nether_hammer'],
];
smithItems.forEach((pair) => {
  PlayerEvents.inventoryChanged(pair[0], event => {
    if (!event.player.stages.has('smith')) {
    event.player.tell(Text.red("Tão... pesado... talvez alguém que trabalhe com metais possa manusear isto."));
    event.player.inventory.removeItem(event.getSlot(), event.item.count);
    event.player.inventory.clear(pair[0]);
  }})
})
